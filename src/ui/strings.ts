/** Polish plural: 1 → one, 2–4 (not 12–14) → few, else many. */
function plural(n: number, one: string, few: string, many: string): string {
  if (n === 1) return one;
  return n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 12 || n % 100 > 14) ? few : many;
}
